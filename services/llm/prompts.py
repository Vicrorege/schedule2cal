PARSE_HOMEWORK_USER = """<<<USER_HOMEWORK_TEXT>>>
{user_text}
<<<END_USER_HOMEWORK_TEXT>>>

Верни только JSON HomeworkParseResult."""


def wrap_homework_user_text(text: str) -> str:
    """Экранирует маркеры в пользовательском тексте, чтобы нельзя было вырваться из блока."""
    sanitized = (
        text.replace("<<<USER_HOMEWORK_TEXT>>>", "«USER_HOMEWORK_TEXT»")
        .replace("<<<END_USER_HOMEWORK_TEXT>>>", "«END_USER_HOMEWORK_TEXT»")
    )
    # ограничение длины — защита от огромных промптов
    if len(sanitized) > 8000:
        sanitized = sanitized[:8000] + "\n…[обрезано]"
    return PARSE_HOMEWORK_USER.format(user_text=sanitized)
